const DICTS: Record<Locale, Partial<Record<MessageKey, string>>> = { es, "pt-BR": ptBR };

/** Valores que se interpolan en un texto: `{n}`, `{amount}`, `{name}`… */
export type MessageVars = Record<string, string | number>;

/** Claves de `es` sin traducción en `locale` (invariante: ninguna; lo verifica la prueba del diccionario). */
export function missingTranslations(locale: Locale): MessageKey[] {
  const dict = DICTS[locale];
  return (Object.keys(es) as MessageKey[]).filter((key) => dict[key] === undefined);
}

/** Pares [clave, texto] del diccionario de `locale`, para verificar marcadores y claves sobrantes. */
export function dictionaryEntries(locale: Locale): [string, string][] {
  return Object.entries(DICTS[locale]).filter((entry): entry is [string, string] => typeof entry[1] === "string");
}

function translate(locale: Locale, key: MessageKey): string {
  return DICTS[locale][key] ?? es[key] ?? key;
}

/**
 * Interpola `{clave}` por su valor; las claves sin valor se dejan tal cual para que el hueco sea
 * visible en pantalla (nunca un texto a medias en silencio).
 */
function interpolate(text: string, vars: MessageVars): string {
  return text.replace(/\{(\w+)\}/g, (match, name: string) => (name in vars ? String(vars[name]) : match));
}

/** Traduce con el idioma vigente (fuera de React: mapeo de errores, cola offline). */
export function t(key: MessageKey): string {
  return translate(getLocale(), key);
}

/** Traduce e interpola: `tf("offline.pendingMany", { n: 3 })` → "3 operaciones…". */
export function tf(key: MessageKey, vars: MessageVars): string {
  return interpolate(t(key), vars);
}

/**
 * Hook de traducción REACTIVO: al cambiar el idioma (menú de usuario) el componente se vuelve a
 * pintar y `t`/`tf` cambian de identidad, así que también se recalculan los `useMemo` que dependan
 * de ellos. `locale` es BCP-47 y sirve para `toLocaleDateString`.
 */
export function useT() {
  const locale = useLocale();
  return useMemo(
    () => ({
      t: (key: MessageKey) => translate(locale, key),
      tf: (key: MessageKey, vars: MessageVars) => interpolate(translate(locale, key), vars),
      locale,
    }),
    [locale],
  );
}
